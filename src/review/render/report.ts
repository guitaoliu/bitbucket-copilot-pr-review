import type {
	InsightReportDataField,
	InsightReportPayload,
} from "../../bitbucket/types.ts";
import type { ReviewerConfig } from "../../config/types.ts";
import { omitUndefined } from "../../shared/object.ts";
import { truncateText } from "../../shared/text.ts";
import { buildPublicationStateFields } from "../publication-state.ts";
import type { ReviewContext, ReviewOutcome } from "../types.ts";
import {
	formatFindingListLines,
	formatFindingLocation,
	formatFindingTypeSummary,
} from "./markdown.ts";

const REPORT_DETAILS_MAX_CHARS = 1900;

export function buildInsightReport(
	config: ReviewerConfig,
	context: ReviewContext,
	review: ReviewOutcome,
): InsightReportPayload {
	const findingTypeSummary = formatFindingTypeSummary(review.findings);
	const findingSummary =
		review.findings.length > 0
			? `\n\nTaxonomy: ${findingTypeSummary ?? "reportable findings"}\n\nTop validated findings:\n${formatFindingListLines(review.findings, formatFindingLocation).join("\n")}`
			: "";
	const data: InsightReportDataField[] = [
		...buildPublicationStateFields({
			revision: context.reviewRevision,
			findingCount: review.findings.length,
		}),
		...(findingTypeSummary
			? [
					{
						title: "Finding taxonomy",
						type: "TEXT" as const,
						value: findingTypeSummary,
					},
				]
			: []),
		{
			title: "Review scope",
			type: "TEXT",
			value: `${context.reviewableFiles.length} reviewable`,
		},
	];

	return omitUndefined({
		title: config.report.title,
		details: truncateText(
			`${review.summary}\n\nAdvisory AI review generated by GitHub Copilot. Only validated findings on reviewable changed files and changed lines are published.${findingSummary}`,
			REPORT_DETAILS_MAX_CHARS,
		),
		result: review.incomplete || review.findings.length > 0 ? "FAIL" : "PASS",
		reporter: config.report.reporter,
		link: config.report.link,
		data,
	}) satisfies InsightReportPayload;
}
